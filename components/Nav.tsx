"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { motion } from "framer-motion";
import { useState } from "react";
import { datasetInfo } from "@/lib/info";
import { model } from "@/lib/model";

const LINKS = [
  { href: "/players", label: "Players" },
  { href: "/compare", label: "Compare" },
  { href: "/whatif", label: "What-If Lab" },
  { href: "/models", label: "Model" },
];

export function Nav() {
  const pathname = usePathname();
  const [open, setOpen] = useState(false);

  return (
    <>
      <header className="sticky top-0 z-50 border-b border-line-soft bg-void/72 backdrop-blur-xl">
        <div className="mx-auto flex h-14 max-w-[1400px] items-center gap-6 px-5 sm:px-8">
          <Link href="/" className="group flex items-center gap-2.5">
            <Mark />
            <span className="text-[13px] font-semibold tracking-[0.18em] text-ink">
              PLAYER<span className="text-a">LAB</span>
            </span>
          </Link>

          <nav className="hidden items-center gap-1 md:flex">
            {LINKS.map((link) => {
              const active = pathname === link.href || pathname.startsWith(`${link.href}/`);
              return (
                <Link
                  key={link.href}
                  href={link.href}
                  className={`relative rounded-full px-3.5 py-1.5 text-[11px] font-semibold tracking-[0.12em] uppercase transition-colors ${
                    active ? "text-ink" : "text-faint hover:text-muted"
                  }`}
                >
                  {active && (
                    <motion.span
                      layoutId="nav-pill"
                      className="absolute inset-0 -z-10 rounded-full border border-line bg-panel-2"
                      transition={{ type: "spring", stiffness: 420, damping: 36 }}
                    />
                  )}
                  {link.label}
                </Link>
              );
            })}
          </nav>

          <div className="ml-auto hidden items-center gap-4 lg:flex">
            <ModelChip />
            <span className="label-xs">
              {datasetInfo.count.toLocaleString()} players · {datasetInfo.nations} nations
            </span>
          </div>

          <button
            onClick={() => setOpen((v) => !v)}
            className="ml-auto flex h-9 w-9 items-center justify-center rounded-lg border border-line text-muted md:hidden"
            aria-label="Toggle navigation"
          >
            <span className="flex flex-col gap-[3px]">
              <span className="block h-px w-4 bg-current" />
              <span className="block h-px w-4 bg-current" />
              <span className="block h-px w-4 bg-current" />
            </span>
          </button>
        </div>

        {open && (
          <motion.div
            initial={{ height: 0, opacity: 0 }}
            animate={{ height: "auto", opacity: 1 }}
            className="overflow-hidden border-t border-line-soft md:hidden"
          >
            <div className="flex flex-col gap-1 px-5 py-4">
              {LINKS.map((link) => (
                <Link
                  key={link.href}
                  href={link.href}
                  onClick={() => setOpen(false)}
                  className="rounded-lg px-3 py-2.5 text-xs font-semibold tracking-[0.12em] text-muted uppercase hover:bg-panel-2 hover:text-ink"
                >
                  {link.label}
                </Link>
              ))}
            </div>
          </motion.div>
        )}
      </header>

      {datasetInfo.synthetic && <SyntheticBanner season={datasetInfo.season} />}
    </>
  );
}

function ModelChip() {
  return (
    <span className="label-xs flex items-center gap-1.5 rounded-full border border-line bg-panel-2/70 px-2.5 py-1.5">
      <span className="relative flex h-1.5 w-1.5">
        <span className="absolute inline-flex h-full w-full rounded-full bg-good" style={{ animation: "pulse-ring 2.4s infinite" }} />
        <span className="relative inline-flex h-1.5 w-1.5 rounded-full bg-good" />
      </span>
      ridge · cv R² {model.segments.outfield.metrics.cv.r2.toFixed(3)}
    </span>
  );
}

export function SyntheticBanner({ season }: { season?: string }) {
  return (
    <div className="border-b border-warn/18 bg-warn/[0.055]">
      <p className="mx-auto max-w-[1400px] px-5 py-2 text-[11px] leading-relaxed text-warn/80 sm:px-8">
        <span className="font-semibold tracking-wide uppercase">Synthetic demo data</span> — generated from
        position archetypes, not official EA SPORTS FC {season ?? "26"} ratings. Every prediction and attribution
        on this site is generated by the model trained on that set.
      </p>
    </div>
  );
}

function Mark() {
  return (
    <span className="relative flex h-7 w-7 items-center justify-center">
      <svg viewBox="0 0 28 28" className="h-7 w-7">
        <defs>
          <linearGradient id="mark-g" x1="0" y1="0" x2="1" y2="1">
            <stop offset="0%" stopColor="var(--color-a)" />
            <stop offset="100%" stopColor="var(--color-b)" />
          </linearGradient>
        </defs>
        <circle cx="14" cy="14" r="11" fill="none" stroke="url(#mark-g)" strokeWidth="1.4" />
        <path d="M14 3 L23 8.5 L23 19.5 L14 25 L5 19.5 L5 8.5 Z" fill="none" stroke="url(#mark-g)" strokeWidth="0.9" opacity="0.55" />
        <circle cx="14" cy="14" r="2.6" fill="url(#mark-g)" />
      </svg>
    </span>
  );
}

export { Mark };
